from datetime import datetime, timezone
from io import BytesIO
from xml.sax.saxutils import escape

from reportlab.lib import colors
from reportlab.lib.pagesizes import A4
from reportlab.lib.styles import ParagraphStyle
from reportlab.lib.units import mm
from reportlab.platypus import (
    Paragraph,
    SimpleDocTemplate,
    Spacer,
    Table,
    TableStyle,
)

BLUE = colors.HexColor("#1D4ED8")
INK = colors.HexColor("#0F172A")
BODY = colors.HexColor("#334155")
MUTED = colors.HexColor("#64748B")
LINE = colors.HexColor("#E2E8F0")
SURFACE = colors.HexColor("#F8FAFC")

STAGES = ("New", "Contacted", "Proposal", "Won", "Lost")


def range_label(days: int | None) -> str:
    return f"Last {days} days" if days else "All time"


def range_slug(days: int | None) -> str:
    return f"last-{days}-days" if days else "all-time"


def _money(value: float) -> str:
    return f"${value:,.2f}"


def _style(name: str, **kwargs) -> ParagraphStyle:
    options = {"fontName": "Helvetica", "textColor": BODY, **kwargs}  # kwargs win
    return ParagraphStyle(name, **options)


BRAND = _style("brand", fontName="Helvetica-Bold", fontSize=18, leading=22, textColor=INK)
TITLE = _style("title", fontName="Helvetica-Bold", fontSize=24, leading=30, textColor=INK)
META = _style("meta", fontSize=10, leading=14, textColor=MUTED)
H2 = _style("h2", fontName="Helvetica-Bold", fontSize=13, leading=18, textColor=INK)
CELL = _style("cell", fontSize=10, leading=14)
EMPTY = _style("empty", fontSize=10, leading=14, textColor=MUTED)
KPI_LABEL = _style("kpil", fontSize=9, leading=12, textColor=MUTED)
KPI_VALUE = _style("kpiv", fontName="Helvetica-Bold", fontSize=17, leading=22, textColor=INK)


def _table(rows: list[list], col_widths: list[float], right_cols: tuple[int, ...] = ()):
    table = Table(rows, colWidths=col_widths, repeatRows=1)
    style = [
        ("BACKGROUND", (0, 0), (-1, 0), BLUE),
        ("TEXTCOLOR", (0, 0), (-1, 0), colors.white),
        ("FONTNAME", (0, 0), (-1, 0), "Helvetica-Bold"),
        ("FONTSIZE", (0, 0), (-1, 0), 9),
        ("TOPPADDING", (0, 0), (-1, -1), 7),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 7),
        ("LEFTPADDING", (0, 0), (-1, -1), 10),
        ("RIGHTPADDING", (0, 0), (-1, -1), 10),
        ("LINEBELOW", (0, 1), (-1, -1), 0.5, LINE),
        ("ROWBACKGROUNDS", (0, 1), (-1, -1), [colors.white, SURFACE]),
    ]
    for col in right_cols:
        style.append(("ALIGN", (col, 0), (col, -1), "RIGHT"))
    table.setStyle(TableStyle(style))
    return table


def _footer(canvas, doc):
    canvas.saveState()
    canvas.setFont("Helvetica", 8)
    canvas.setFillColor(MUTED)
    canvas.drawString(doc.leftMargin, 10 * mm, "Generated by ClientDesk")
    canvas.drawRightString(A4[0] - doc.rightMargin, 10 * mm, f"Page {doc.page}")
    canvas.restoreState()


def _format_point(date_str: str, days: int | None) -> str:
    d = datetime.strptime(date_str, "%Y-%m-%d")
    # All time is grouped by month, 7 and 30 days by day
    return d.strftime("%B %Y") if days is None else d.strftime("%b %d, %Y")


def build_report_pdf(report: dict, *, days: int | None, user_name: str) -> bytes:
    buffer = BytesIO()
    doc = SimpleDocTemplate(
        buffer,
        pagesize=A4,
        leftMargin=18 * mm,
        rightMargin=18 * mm,
        topMargin=16 * mm,
        bottomMargin=20 * mm,
        title=f"ClientDesk report - {range_label(days)}",
        author="ClientDesk",
    )
    width = A4[0] - doc.leftMargin - doc.rightMargin

    by_stage = report["by_stage"]
    created = sum(by_stage.values())
    won, lost = by_stage.get("Won", 0), by_stage.get("Lost", 0)
    win_rate = round(won / (won + lost) * 100) if won + lost else 0
    paid_total = sum(p["total"] for p in report["revenue"])

    generated = datetime.now(timezone.utc).strftime("%b %d, %Y")
    story = [
        Paragraph('Client<font color="#1D4ED8">Desk</font>', BRAND),
        Spacer(1, 6 * mm),
        Paragraph("Sales report", TITLE),
        Spacer(1, 1.5 * mm),
        Paragraph(
            f"{escape(range_label(days))} | Prepared for {escape(user_name)} | {generated}",
            META,
        ),
        Spacer(1, 8 * mm),
    ]

    # Summary cards
    def kpi(label: str, value: str):
        return [Paragraph(label, KPI_LABEL), Paragraph(value, KPI_VALUE)]

    kpis = Table(
        [[
            kpi("Offers created", str(created)),
            kpi("Offers won", str(won)),
            kpi("Win rate", f"{win_rate}%"),
            kpi("Paid revenue", _money(paid_total)),
        ]],
        colWidths=[width / 4] * 4,
    )
    kpis.setStyle(TableStyle([
        ("BOX", (0, 0), (-1, -1), 0.75, LINE),
        ("INNERGRID", (0, 0), (-1, -1), 0.75, LINE),
        ("BACKGROUND", (0, 0), (-1, -1), SURFACE),
        ("TOPPADDING", (0, 0), (-1, -1), 10),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 10),
        ("LEFTPADDING", (0, 0), (-1, -1), 12),
        ("VALIGN", (0, 0), (-1, -1), "TOP"),
    ]))
    story += [kpis, Spacer(1, 9 * mm)]

    # Offers by stage
    story += [Paragraph("Offers by stage", H2), Spacer(1, 3 * mm)]
    stage_rows = [["Stage", "Offers"]] + [[s, str(by_stage.get(s, 0))] for s in STAGES]
    story += [
        _table(stage_rows, [width * 0.7, width * 0.3], right_cols=(1,)),
        Spacer(1, 9 * mm),
    ]

    # Paid revenue
    story += [
        Paragraph("Paid revenue per month" if days is None else "Paid revenue per day", H2),
        Spacer(1, 3 * mm),
    ]
    if report["revenue"]:
        rows = [["Period", "Revenue"]] + [
            [_format_point(p["date"], days), _money(p["total"])] for p in report["revenue"]
        ]
        story.append(_table(rows, [width * 0.7, width * 0.3], right_cols=(1,)))
    else:
        story.append(Paragraph("No paid invoices in this period.", EMPTY))
    story.append(Spacer(1, 9 * mm))

    # Top contacts
    story += [Paragraph("Top contacts by won value", H2), Spacer(1, 3 * mm)]
    if report["top_contacts"]:
        rows = [["Name", "Company", "Won offers", "Total"]] + [
            [
                Paragraph(escape(c["name"]), CELL),   # escape: names can contain < or &
                Paragraph(escape(c["company"]), CELL),
                str(c["count"]),
                _money(c["total"]),
            ]
            for c in report["top_contacts"]
        ]
        story.append(
            _table(rows, [width * 0.3, width * 0.3, width * 0.17, width * 0.23], right_cols=(2, 3))
        )
    else:
        story.append(Paragraph("No offers were won in this period.", EMPTY))

    doc.build(story, onFirstPage=_footer, onLaterPages=_footer)
    return buffer.getvalue()