from app.portal.models import ContactOut
from datetime import datetime, timezone

from sqlalchemy import func, or_, select
from sqlalchemy.orm import Session

from shared_package.db.model.contacts import Contacts
from app.services.error import ConflictError, NotFoundError

def to_contact_out(contact) -> ContactOut:
    # Our DB column is contact_id, the frontend expects id
    return ContactOut(
        id=contact.contact_id,
        name=contact.name,
        email=contact.email,
        phone=contact.phone,
        company=contact.company,
        created_at=contact.created_at,
    )


def _email_exists(
    db: Session, user_id: str, email: str, exclude_id: str | None = None
) -> bool:
    """True if this user already has a (non-deleted) contact with this email."""
    stmt = select(Contacts.contact_id).where(
        Contacts.user_id == user_id,
        Contacts.deleted_at.is_(None),
        func.lower(Contacts.email) == email.lower(),
    )
    if exclude_id:  # when editing, ignore the contact itself
        stmt = stmt.where(Contacts.contact_id != exclude_id)
    return db.scalar(stmt) is not None

def _contact_filters(user_id: str, q: str | None) -> list:
    """The WHERE conditions shared by the count query and the page query."""
    conditions = [Contacts.user_id == user_id, Contacts.deleted_at.is_(None)]
    if q and q.strip():
        like = f"%{q.strip().lower()}%"
        conditions.append(
            or_(
                func.lower(Contacts.name).like(like),
                func.lower(Contacts.company).like(like),
                func.lower(Contacts.email).like(like),
            )
        )
    return conditions

def list_contacts(
    db: Session,
    user_id: str,
    q: str | None = None,
    page: int = 1,
    page_size: int = 20,
) -> tuple[list[Contacts], int]:
    """Returns (contacts on this page, total number of matching contacts)."""
    conditions = _contact_filters(user_id, q)

    total = db.scalar(
        select(func.count()).select_from(Contacts).where(*conditions)
    ) or 0

    contacts = db.scalars(
        select(Contacts)
        .where(*conditions)
        # contact_id breaks ties, so rows never jump between pages
        .order_by(Contacts.created_at.desc(), Contacts.contact_id)
        .offset((page - 1) * page_size)   # skip the earlier pages
        .limit(page_size)                 # take one page
    ).all()

    return list(contacts), total


def get_contact(db: Session, user_id: str, contact_id: str) -> Contacts:
    contact = db.scalar(
        select(Contacts).where(
            Contacts.contact_id == contact_id,
            Contacts.user_id == user_id,       # only YOUR contacts
            Contacts.deleted_at.is_(None),     # not deleted
        )
    )
    if contact is None:
        raise NotFoundError("Contact not found.")
    return contact


def create_contact(
    db: Session,
    user_id: str,
    *,
    name: str,
    email: str,
    company: str,
    phone: str | None = None,
) -> Contacts:
    if _email_exists(db, user_id, email):
        raise ConflictError("You already have a contact with this email.")

    contact = Contacts(
        user_id=user_id,
        name=name.strip(),
        email=email.strip(),
        company=company.strip(),
        phone=(phone or "").strip() or None,
    )
    db.add(contact)
    db.commit()
    db.refresh(contact)   # reloads id and created_at generated by the DB
    return contact


def update_contact(
    db: Session, user_id: str, contact_id: str, changes: dict
) -> Contacts:
    contact = get_contact(db, user_id, contact_id)   # 404 if not yours

    for field, value in changes.items():
        if field == "phone":
            contact.phone = (value or "").strip() or None   # phone may be cleared
            continue
        if value is None:
            continue                                        # name/email/company can't be cleared
        value = value.strip()
        if field == "email" and _email_exists(db, user_id, value, exclude_id=contact_id):
            raise ConflictError("You already have a contact with this email.")
        setattr(contact, field, value)

    db.commit()
    db.refresh(contact)
    return contact


def delete_contact(db: Session, user_id: str, contact_id: str) -> None:
    contact = get_contact(db, user_id, contact_id)
    contact.deleted_at = datetime.now(timezone.utc)   # soft delete
    db.commit()